/// What was right-clicked; selects a context-menu layout.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Context {
    /// A hierarchy row or a viewport object.
    Entity,
    /// Empty hierarchy space.
    Hierarchy,
    /// Empty viewport space.
    Viewport,
    /// An asset tile or row.
    Asset,
    /// A folder.
    Folder,
    /// Empty asset browser space.
    Assets,
    /// An inspector field.
    Field,
    /// An inspector component header.
    Component,
    /// A dock tab or panel header.
    Tab,
    /// A graph node.
    Node,
    /// Empty graph canvas.
    Canvas,
    /// A console row.
    Console,
    /// A real immutable transaction in History.
    History,
    /// A profiler span or frame.
    Profiler,
    /// A status bar chip.
    Status,
    /// The Play cluster's mode button.
    Play,
    /// A VFX module row.
    Module,
    /// Viewport toolbar: camera views.
    Camera,
    /// Viewport camera fly speed presets.
    CameraSpeed,
    /// Snap increments when the viewport is too narrow for three value buttons.
    Snapping,
    /// Viewport toolbar: view modes.
    ViewModes,
    /// Viewport toolbar: show flags.
    Show,
    /// Game view toolbar: aspect presets.
    GameAspect,
    /// Hierarchy toolbar: type filters.
    HierarchyFilter,
}
