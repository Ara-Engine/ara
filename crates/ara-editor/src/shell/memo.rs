//! Per-panel markup memoization. A memoized panel's markup and the bindings it
//! registered are reused while a digest of everything it reads is unchanged; its body
//! part is then byte-identical, so `Ui::reconcile_parts` keeps it wholesale. In check
//! mode (`ARA_EDITOR_MEMO_CHECK=1`, set for every `cargo test`) each reuse is generated
//! again and must match: a difference means the panel's digest misses an input.
use super::*;
use std::hash::{DefaultHasher, Hash, Hasher};

/// A panel's last markup, the bindings it registered and the digest it was built for.
pub(super) struct Memo {
    key: u64,
    markup: String,
    bindings: Vec<(u64, Binding)>,
}

/// A digest of a panel's inputs (floats as their bits).
pub(super) fn digest(inputs: impl Hash) -> u64 {
    let mut hasher = DefaultHasher::new();
    inputs.hash(&mut hasher);
    hasher.finish()
}

impl Shell {
    /// Append `name`'s markup to `out`: generated by `generate`, or reused when `key`
    /// (a [`digest`] of everything the generator reads) is the last one's. Bindings the
    /// generator registered are registered again on reuse; its other effects (row
    /// models, thumbnail requests) persist on the shell anyway.
    pub(super) fn memoized(
        &mut self,
        name: &'static str,
        key: u64,
        out: &mut String,
        generate: impl Fn(&mut Self, &mut String),
    ) {
        if let Some(memo) = self
            .memos
            .get(name)
            .filter(|memo| self.memo_enabled && memo.key == key)
        {
            out.push_str(&memo.markup);
            self.bindings.extend(memo.bindings.iter().cloned());
            if self.memo_check {
                let (markup, bindings) = self.captured(&generate);
                let memo = &self.memos[name];
                assert!(
                    markup == memo.markup && bindings == memo.bindings,
                    "memoized panel `{name}` reused stale markup: its digest misses an input\nreused:    {}\ngenerated: {markup}",
                    memo.markup
                );
            }
            return;
        }
        let (markup, bindings) = self.captured(&generate);
        out.push_str(&markup);
        self.bindings.extend(bindings.iter().cloned());
        self.memos.insert(
            name,
            Memo {
                key,
                markup,
                bindings,
            },
        );
    }
    /// Run `generate` alone: its markup and the bindings it registered.
    fn captured(
        &mut self,
        generate: &impl Fn(&mut Self, &mut String),
    ) -> (String, Vec<(u64, Binding)>) {
        let outer = std::mem::take(&mut self.bindings);
        let mut markup = String::new();
        generate(self, &mut markup);
        let bindings = std::mem::replace(&mut self.bindings, outer);
        (markup, bindings.into_iter().collect())
    }
}
