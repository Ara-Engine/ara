use crate::{ParamKind, Result, Table, error};
use std::collections::BTreeSet;
use std::fmt::Write;

/// Generated source artifacts; hosts persist them alongside game bindings.
pub struct GeneratedKeys {
    /// Rust typed key constants and parameter structures.
    pub rust: String,
    /// C# typed key constants and parameter records, with no engine object state.
    pub csharp: String,
}

/// Generates statically paired keys/parameters, rejecting ambiguous identifier names.
pub fn generate_keys(table: &Table) -> Result<GeneratedKeys> {
    let mut rust = String::from(
        "// Generated by ara-l10n; edit the source table.\nuse ara_l10n::{Argument, Arguments, Decimal, Key, Parameters};\n",
    );
    let mut csharp = String::from(
        "// Generated by ara-l10n; edit the source table.\nnamespace Ara.Localization;\npublic readonly record struct L10nKey<T>(string Value);\npublic readonly record struct Money(decimal Amount, string Currency);\npublic static class Keys\n{\n",
    );
    let mut names = BTreeSet::from(["Keys".to_string()]);
    for entry in table.entries() {
        let name = pascal(&entry.key);
        let constant = entry.key.replace('.', "_").to_ascii_uppercase();
        if !names.insert(name.clone()) || !names.insert(format!("const:{constant}")) {
            return Err(error("localization keys collide as generated identifiers"));
        }
        let params = format!("{name}Params");
        if !names.insert(params.clone()) {
            return Err(error(
                "localization parameter type collides with a generated key",
            ));
        }
        writeln!(
            rust,
            "/// Parameters for `{}`.\npub struct {params} {{",
            entry.key
        )
        .map_err(|e| error(e.to_string()))?;
        let mut fields = Vec::new();
        let mut parameter_names = BTreeSet::new();
        for (field, kind) in &entry.params {
            let cs_field = pascal(field);
            if !parameter_names.insert(cs_field.clone()) {
                return Err(error("parameter names collide in C#"));
            }
            let (rs, cs) = match kind {
                ParamKind::Text => ("String", "string"),
                ParamKind::Number => ("Decimal", "decimal"),
                ParamKind::Date => ("ara_l10n::IsoDate", "System.DateOnly"),
                ParamKind::Currency => ("ara_l10n::Money", "Money"),
            };
            writeln!(
                rust,
                "    /// Value for `{field}`.\n    pub r#{field}: {rs},"
            )
            .map_err(|e| error(e.to_string()))?;
            fields.push(format!("{cs} {cs_field}"));
        }
        rust.push_str("}\n");
        writeln!(rust, "impl Parameters for {params} {{\n    fn into_arguments(self) -> Arguments {{\n        Arguments::from([").map_err(|e| error(e.to_string()))?;
        for (field, kind) in &entry.params {
            let value = match kind {
                ParamKind::Text => format!("Argument::Text(self.r#{field})"),
                ParamKind::Number => format!("Argument::Number(self.r#{field})"),
                ParamKind::Date => format!("Argument::Date(self.r#{field})"),
                ParamKind::Currency => format!(
                    "Argument::Currency {{ amount: self.r#{field}.amount, code: self.r#{field}.code }}"
                ),
            };
            writeln!(rust, "            ({field:?}.into(), {value}),")
                .map_err(|e| error(e.to_string()))?;
        }
        writeln!(rust, "        ])\n    }}\n}}\n/// Typed lookup for `{}`.\npub const {constant}: Key<{params}> = Key::new({:?});", entry.key, entry.key).map_err(|e| error(e.to_string()))?;
        writeln!(csharp, "    public readonly record struct {params}({});\n    public static readonly L10nKey<{params}> {name} = new({:?});", fields.join(", "), entry.key).map_err(|e| error(e.to_string()))?;
    }
    csharp.push_str("}\n");
    Ok(GeneratedKeys { rust, csharp })
}

pub(crate) fn pascal(value: &str) -> String {
    value
        .split(['.', '_'])
        .filter(|s| !s.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            let mut result = chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string())
                .unwrap_or_default();
            result.extend(chars);
            result
        })
        .collect()
}
