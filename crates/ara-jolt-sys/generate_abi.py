"""Regenerate C declarations and layout probes from the deliberately small Rust ABI."""
from pathlib import Path
import re

root = Path(__file__).parent
source = (root / "src/types.rs").read_text() + (root / "src/lib.rs").read_text()
types = {"f32": "float", "u32": "uint32_t", "i32": "int32_t", "u64": "uint64_t", "u8": "uint8_t", "usize": "size_t", "c_char": "char", "()": "void"}

def ty(s):
    s = s.strip()
    if s.startswith("*const "):
        return "const " + ty(s[7:]) + "*"
    if s.startswith("*mut "):
        return ty(s[5:]) + "*"
    if s not in types and not re.fullmatch(r"Ara\w+",s):
        raise ValueError(f"unsupported ABI type: {s!r}")
    return types.get(s, s)

header = ["// Generated by generate_abi.py from src/lib.rs and src/types.rs. Do not edit.", "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "typedef struct AraWorld AraWorld;", '#ifdef __cplusplus\nextern "C" {\n#endif']
layout = []
rust_layout = []
for name, body in re.findall(r"pub struct (Ara\w+) \{(.*?)\n\}", source, re.S):
    if name == "AraWorld":
        continue
    header.append("typedef struct {")
    layout += [f"sizeof({name})", f"alignof({name})"]
    rust_layout += [f"size_of::<{name}>() as u32", f"align_of::<{name}>() as u32"]
    for field, field_type in re.findall(r"pub (\w+): ([^,\n]+),", body):
        array = re.fullmatch(r"\[(\w+); (\d+)\]", field_type)
        header.append(f"    {ty(array[1])} {field}[{array[2]}];" if array else f"    {ty(field_type)} {field};")
        layout.append(f"offsetof({name}, {field})")
        rust_layout.append(f"core::mem::offset_of!({name}, {field}) as u32")
    header.append(f"}} {name};")
functions=re.findall(r"pub fn (ara_\w+)\(([^)]*)\)\s*(?:->\s*([^;]+))?;",source,re.S)
assert len(functions)==len(re.findall(r"pub fn ara_",source)),"ABI parser skipped a declaration"
for name, params, result in functions:
    args = [ty(t) + " " + n for n, t in (p.strip().split(": ", 1) for p in params.split(",") if p.strip())]
    header.append(f"{ty(result or '()')} {name}({', '.join(args) or 'void'});")
header.append('#ifdef __cplusplus\n}\n#endif\n')
(root / "shim/ara_jolt.h").write_text("\n".join(header), newline="\n")
(root / "shim/abi_layout.inc").write_text(",\n".join(layout) + "\n", newline="\n")
test = """// Generated layout verification, including every field offset.
#[test]
fn c_and_rust_layouts_match() {
    use super::*;
    let expected = [
""" + ",\n".join(rust_layout) + """
    ];
    let mut actual = vec![0; expected.len()];
    // SAFETY: output has the exact capacity passed to the native layout probe.
    let count = unsafe { ara_abi_layout(actual.as_mut_ptr(), actual.len() as u32) };
    assert_eq!(count as usize, expected.len());
    assert_eq!(actual, expected);
}
"""
(root / "src/layout_test.rs").write_text(test, newline="\n")
