//! Regenerates `src/icons.rs` from the Lucide SVGs in `icons/`: every element becomes SVG
//! path data (circles, rects, lines and polylines are converted) on Lucide's 24-unit grid, as
//! a typed `Icon` constant per file. `cargo run -p ara-kit --example gen-icons`.
use std::{collections::BTreeMap, fmt::Write, fs, path::Path};

fn main() -> anyhow::Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut icons = BTreeMap::new();
    for entry in fs::read_dir(root.join("icons"))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "svg") {
            let name = path
                .file_stem()
                .and_then(|s| s.to_str())
                .expect("UTF-8 icon name")
                .to_owned();
            let d = path_data(&fs::read_to_string(&path)?)
                .map_err(|e| anyhow::anyhow!("{name}: {e}"))?;
            icons.insert(name, d);
        }
    }
    let mut out = String::from(
        "//! Generated by `cargo run -p ara-kit --example gen-icons` from `icons/*.svg` (Lucide,\n\
         //! ISC; `icons/SOURCE.md`). Do not edit: add an SVG there and run it again.\n\
         //! Each icon is SVG path data on Lucide's 24-unit grid, stroked with round caps.\n\
         #![allow(missing_docs)]\n\
         use stillkit::icons::{Icon, IconPath};\n\n",
    );
    for (name, d) in &icons {
        let id = name.to_uppercase().replace('-', "_");
        writeln!(
            out,
            "static P_{id}: IconPath = IconPath {{ name: \"{name}\", d: \"{d}\" }};"
        )?;
        writeln!(out, "pub const {id}: Icon = Icon::Path(&P_{id});")?;
    }
    out.push_str("\n/// Every icon by its Lucide name, sorted, for data-driven callers (command tables).\npub const ALL: &[(&str, Icon)] = &[\n");
    for name in icons.keys() {
        writeln!(
            out,
            "    (\"{name}\", {}),",
            name.to_uppercase().replace('-', "_")
        )?;
    }
    out.push_str("];\n\n/// The icon with this Lucide name.\npub fn named(name: &str) -> Option<Icon> {\n    ALL.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| ALL[i].1)\n}\n");
    fs::write(root.join("src/icons.rs"), out)?;
    println!("{} icons", icons.len());
    Ok(())
}

/// The `d` of every drawable element in an SVG, joined.
fn path_data(svg: &str) -> Result<String, String> {
    let body = &svg[svg.find("<svg").ok_or("no <svg>")?..];
    let body =
        &body[body.find('>').ok_or("open <svg")? + 1..body.rfind("</svg>").ok_or("no </svg>")?];
    let mut d = String::new();
    let mut rest = body;
    while let Some(start) = rest.find('<') {
        let end = rest[start..].find('>').ok_or("open tag")? + start;
        let tag = rest[start + 1..end].trim_end_matches('/').trim();
        rest = &rest[end + 1..];
        let (name, attrs) = tag.split_once(char::is_whitespace).unwrap_or((tag, ""));
        let attr = |key: &str| -> Option<f32> { value(attrs, key).and_then(|v| v.parse().ok()) };
        let num = |key: &str| attr(key).ok_or(format!("<{name}> {key}"));
        match name {
            "path" => {
                let raw = value(attrs, "d").ok_or("path d")?.trim();
                // A leading relative `m` is absolute in its own path but not once joined.
                match raw.strip_prefix('m') {
                    Some(tail) => {
                        let (nums, after) = numbers(tail);
                        let [x, y, more @ ..] = nums.as_slice() else {
                            return Err("m needs x y".into());
                        };
                        write!(d, "M{x} {y}").ok();
                        // Further pairs are implicit relative line-tos.
                        if !more.is_empty() {
                            write!(d, "l{}", more.join(" ")).ok();
                        }
                        d.push_str(after);
                    }
                    None => d.push_str(raw),
                }
            }
            "circle" => {
                let (cx, cy, r) = (num("cx")?, num("cy")?, num("r")?);
                write!(
                    d,
                    "M{} {cy}a{r} {r} 0 1 0 {} 0a{r} {r} 0 1 0 {} 0Z",
                    cx - r,
                    2. * r,
                    -2. * r
                )
                .ok();
            }
            "ellipse" => {
                let (cx, cy, rx, ry) = (num("cx")?, num("cy")?, num("rx")?, num("ry")?);
                write!(
                    d,
                    "M{} {cy}a{rx} {ry} 0 1 0 {} 0a{rx} {ry} 0 1 0 {} 0Z",
                    cx - rx,
                    2. * rx,
                    -2. * rx
                )
                .ok();
            }
            "rect" => {
                let (x, y, w, h) = (
                    attr("x").unwrap_or(0.),
                    attr("y").unwrap_or(0.),
                    num("width")?,
                    num("height")?,
                );
                let r = attr("rx")
                    .or(attr("ry"))
                    .unwrap_or(0.)
                    .min(w / 2.)
                    .min(h / 2.);
                if r == 0. {
                    write!(d, "M{x} {y}h{w}v{h}h{}Z", -w).ok();
                } else {
                    write!(
                        d,
                        "M{} {y}h{}a{r} {r} 0 0 1 {r} {r}v{}a{r} {r} 0 0 1 {} {r}h{}a{r} {r} 0 0 1 {} {}v{}a{r} {r} 0 0 1 {r} {}Z",
                        x + r,
                        w - 2. * r,
                        h - 2. * r,
                        -r,
                        -(w - 2. * r),
                        -r,
                        -r,
                        -(h - 2. * r),
                        -r
                    )
                    .ok();
                }
            }
            "line" => {
                write!(
                    d,
                    "M{} {}L{} {}",
                    num("x1")?,
                    num("y1")?,
                    num("x2")?,
                    num("y2")?
                )
                .ok();
            }
            "polyline" | "polygon" => {
                let p: Vec<&str> = value(attrs, "points")
                    .ok_or("points")?
                    .split([' ', ','])
                    .filter(|s| !s.is_empty())
                    .collect();
                write!(d, "M{} {}", p[0], p[1]).ok();
                for xy in p[2..].chunks(2) {
                    write!(d, "L{} {}", xy[0], xy[1]).ok();
                }
                if name == "polygon" {
                    d.push('Z');
                }
            }
            _ => return Err(format!("unsupported <{name}>")),
        }
    }
    Ok(d)
}

/// An attribute's value in a tag's attribute text.
fn value<'a>(attrs: &'a str, key: &str) -> Option<&'a str> {
    let mut rest = attrs;
    while let Some(i) = rest.find(key) {
        let before_ok = i == 0 || rest.as_bytes()[i - 1].is_ascii_whitespace();
        let after = &rest[i + key.len()..];
        if before_ok && let Some(v) = after.trim_start().strip_prefix('=') {
            let v = v.trim_start().strip_prefix('"')?;
            return v.find('"').map(|e| &v[..e]);
        }
        rest = &rest[i + key.len()..];
    }
    None
}

/// The numbers at the start of SVG path data (compact forms like `1.5.5` and `2-3` split),
/// and the text from the first command letter on.
fn numbers(s: &str) -> (Vec<String>, &str) {
    let mut out = Vec::new();
    let b = s.as_bytes();
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b' ' | b',' | b'\n' | b'\t' => i += 1,
            c if c.is_ascii_alphabetic() => break,
            _ => {
                let start = i;
                let (mut dot, mut digits) = (false, false);
                if matches!(b[i], b'-' | b'+') {
                    i += 1;
                }
                while i < b.len() {
                    match b[i] {
                        b'0'..=b'9' => digits = true,
                        b'.' if !dot => dot = true,
                        _ => break,
                    }
                    i += 1;
                }
                if !digits {
                    break;
                }
                out.push(s[start..i].to_owned());
            }
        }
    }
    (out, &s[i..])
}
