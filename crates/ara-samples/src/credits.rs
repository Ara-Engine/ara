//! `THIRD_PARTY_ASSETS.md`, generated from the lock so attribution never drifts.
use crate::lock::{Kind, Lock};
use std::fmt::Write;

/// The attribution document: one table row per asset, grouped by license.
pub fn markdown(lock: &Lock) -> String {
    let mut out = String::from(
        "# Third-party assets\n\n\
         Generated by `ara-samples credits` from `assets.lock.json`; do not edit by hand.\n\n\
         None of these files are committed. `cargo run -p ara-samples -- fetch` downloads\n\
         them from the pinned URLs below, verifies each file's BLAKE3 and places them in the\n\
         ignored `assets/third_party/` folder of the projects that use them. Scenes, layout,\n\
         lighting and the generated kit geometry are original Ara work.\n",
    );
    let mut licenses: Vec<&str> = lock.assets.iter().map(|a| a.license.as_str()).collect();
    licenses.sort();
    licenses.dedup();
    for license in licenses {
        let note = match license {
            "CC0-1.0" => {
                "[CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/): public domain; credit given as a courtesy."
            }
            "CC-BY-4.0" => {
                "[CC BY 4.0](https://creativecommons.org/licenses/by/4.0/): attribution required (below); no changes were made to the files."
            }
            _ => "See the source page for the license terms.",
        };
        let _ = write!(
            out,
            "\n## {license}\n\n{note}\n\n| Asset | Kind | Authors | Used by | Source |\n|---|---|---|---|---|\n"
        );
        for asset in lock.assets.iter().filter(|a| a.license == license) {
            let kind = match asset.kind {
                Kind::Model => "model",
                Kind::Texture => "texture",
                Kind::Hdri => "HDRI",
                Kind::Character => "character",
                Kind::Audio => "audio",
                Kind::Archive => "asset pack",
                Kind::Font => "font",
            };
            let _ = writeln!(
                out,
                "| {} (`{}`) | {kind} | {} | {} | <{}> |",
                asset.title,
                asset.id,
                asset.authors.join(", "),
                asset.projects.join(", "),
                asset.source
            );
        }
    }
    out
}
