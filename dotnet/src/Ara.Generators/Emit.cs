using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Ara.Generators;

/// <summary>Writes the generated C# for each model and the module's <c>Register</c> method.</summary>
public static class Emit
{
    const string Unsafe = "global::System.Runtime.CompilerServices.Unsafe";
    const string Hidden = "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]";

    sealed class Code
    {
        readonly StringBuilder _sb = new();
        int _indent;

        public Code Line(string s = "")
        {
            if (s.Length > 0) _sb.Append(' ', _indent * 4).Append(s);
            _sb.Append('\n');
            return this;
        }

        public Code Open(string header) { Line(header); Line("{"); _indent++; return this; }

        public Code Close() { _indent--; return Line("}"); }

        public override string ToString() => _sb.ToString();
    }

    static Code Header() => new Code()
        .Line("// <auto-generated/>")
        .Line("#nullable enable")
        .Line("#pragma warning disable CS1591, CS0649");

    /// <summary>Wraps <paramref name="body"/> in the shell's namespace, enclosing types and partial declaration.</summary>
    static string InShell(Shell shell, string? baseList, Action<Code> body)
    {
        var c = Header();
        var depth = 0;
        if (shell.Namespace is { } ns) { c.Open("namespace " + ns); depth++; }
        foreach (var container in shell.Containers) { c.Open(container); depth++; }
        c.Open(shell.Header + (baseList is null ? "" : " : " + baseList));
        body(c);
        c.Close();
        for (var i = 0; i < depth; i++) c.Close();
        return c.ToString();
    }

    static string Short(Shell s) => s.Header.Split(' ').Last();

    static void Offsets(Code c, string type, IEnumerable<string> fields, string method = "__AraOffsets")
    {
        c.Line(Hidden);
        c.Open($"internal static unsafe int[] {method}()");
        c.Line($"var v = default({type});");
        c.Line("var b = (byte*)" + Unsafe + ".AsPointer(ref v);");
        c.Line("return [" + string.Join(", ", fields.Select(f => $"(int)((byte*){Unsafe}.AsPointer(ref v.{f}) - b)")) + "];");
        c.Close();
    }

    /// <summary>The partial of a component, resource or cue struct: its index and offsets.</summary>
    public static string Data(DataModel m)
    {
        var self = Short(m.Shell);
        var (iface, prop) = m.Role switch
        {
            "Resource" => ("IResource", "ResourceIndex"),
            "Cue" => ("ICue", "CueIndex"),
            _ => ("IComponent", "TypeIndex"),
        };
        return InShell(m.Shell, $"global::Ara.{iface}<{self}>", c =>
        {
            c.Line(Hidden).Line("internal static uint __araIndex = uint.MaxValue;");
            c.Line("/// <summary>Script index, assigned by the host when the module registers.</summary>");
            c.Line($"public static uint {prop} => __araIndex;");
            Offsets(c, self, m.Fields);
        });
    }

    /// <summary>The chunk-batched entry point of a <c>[Query]</c> system.</summary>
    public static string Query(SystemModel m) => InShell(m.Shell, null, c =>
    {
        c.Line("/// <summary>Runs <c>" + m.Method + "</c> over one chunk (one call per contiguous run of ECS rows).</summary>");
        c.Line(Hidden);
        c.Open($"internal static unsafe void __AraRun_{m.Method}(global::Ara.Hosting.SystemCall* call)");
        c.Line("int n = (int)call->Len;");
        int col = 0, res = 0;
        var args = new List<string>();
        var needEntities = m.Params.Any(p => p.Kind is "entity" or "rng");
        if (needEntities) c.Line("var entities = (global::Ara.Entity*)call->Entities;");
        foreach (var p in m.Params)
        {
            switch (p.Kind)
            {
                case "column":
                    c.Line($"ref var c{col} = ref {Unsafe}.AsRef<{p.CsType}>(call->Columns[{col}]);");
                    args.Add($"{Pass(p.RefKind)}{Unsafe}.Add(ref c{col}, i)");
                    col++;
                    break;
                case "resource":
                    c.Line($"ref var r{res} = ref {Unsafe}.AsRef<{p.CsType}>(call->Resources[{res}]);");
                    args.Add($"{Pass(p.RefKind)}r{res}");
                    res++;
                    break;
                case "entity": args.Add("entities[i]"); break;
                case "tick": args.Add("in *call->Tick"); break;
                case "rng": args.Add("ref rng"); break;
                case "commands": args.Add(Pass(p.RefKind) + "cmds"); break;
            }
        }
        if (m.Params.Any(p => p.Kind == "commands")) c.Line("var cmds = global::Ara.Commands.FromCall(call->Commands);");
        c.Open("for (int i = 0; i < n; i++)");
        if (m.Params.Any(p => p.Kind == "rng")) c.Line($"var rng = global::Ara.Rng.For(in *call->Tick, {StableHash(m.Name)}u, entities[i]);");
        c.Line($"{m.Method}({string.Join(", ", args)});");
        c.Close();
        c.Close();
    });

    static string Pass(string refKind) => refKind switch { "ref" => "ref ", "in" => "in ", _ => "" };

    /// <summary>A behaviour's data component and its property implementations.</summary>
    public static string Behaviour(BehaviourModel m) => InShell(m.Shell, null, c =>
    {
        c.Line($"/// <summary>ECS data of <see cref=\"{m.SchemaName}\"/>: one column per [Property] (schema component <c>{m.SchemaName}</c>).</summary>");
        c.Open("public partial struct Data : global::Ara.IComponent<Data>");
        foreach (var p in m.Props)
        {
            c.Line("/// <summary>" + Xml(p.Doc) + "</summary>");
            c.Line($"public {p.CsType} {p.Name};");
        }
        c.Line(Hidden).Line("internal static uint __araIndex = uint.MaxValue;");
        c.Line("/// <summary>Script component index, assigned by the host when the module registers.</summary>");
        c.Line("public static uint TypeIndex => __araIndex;");
        Offsets(c, "Data", m.Props.Select(p => p.Name));
        c.Close();
        foreach (var p in m.Props)
        {
            var accessors = new List<string>();
            if (p.HasGet) accessors.Add($"get => AraData<Data>().{p.Name};");
            if (p.SetKeyword is { } set) accessors.Add($"{set} => AraData<Data>().{p.Name} = value;");
            c.Line($"{p.Modifiers} {p.CsType} {p.Name} {{ {string.Join(" ", accessors)} }}");
        }
    });

    /// <summary>A command's params struct and its entry point.</summary>
    public static string Command(CommandModel m) => InShell(m.Shell, null, c =>
    {
        var values = m.Params.Where(p => p.Kind == "value").ToList();
        c.Line($"/// <summary>Params of the <c>{Xml(m.Name)}</c> command (schema type <c>{m.ParamsType}</c>).</summary>");
        c.Open("public struct Params");
        foreach (var p in values)
        {
            c.Line($"/// <summary>The <c>{p.Name}</c> parameter.</summary>");
            c.Line($"public {p.CsType} {Schema.Pascal(p.Name)};");
        }
        c.Close();
        Offsets(c, "Params", values.Select(p => Schema.Pascal(p.Name)), "__AraParamsOffsets");
        c.Line("/// <summary>Runs one call: binds params and components, then maps the result to an ABI status.</summary>");
        c.Line(Hidden);
        c.Open("internal static unsafe int __AraInvoke(global::Ara.Hosting.CommandCall* call)");
        c.Line("ref readonly var p = ref *(Params*)call->Params;");
        c.Line("var ctx = new global::Ara.CommandContext(call);");
        var target = m.Params.FirstOrDefault(p => p.Kind == "value" && p.CsType == "global::Ara.Entity");
        var args = new List<string> { "ref ctx" };
        var k = 0;
        foreach (var p in m.Params)
        {
            if (p.Kind == "value") { args.Add("p." + Schema.Pascal(p.Name)); continue; }
            c.Line($"var __c{k} = global::Ara.World.Ptr<{p.CsType}>(p.{Schema.Pascal(target?.Name ?? "")}, {(p.RefKind == "ref" ? "true" : "false")});");
            c.Line($"if (__c{k} == null) return ctx.MissingComponent(\"{p.SchemaName}\");");
            args.Add($"{Pass(p.RefKind)}*__c{k}");
            k++;
        }
        c.Line($"return ctx.Finish(Execute({string.Join(", ", args)}));");
        c.Close();
    });

    /// <summary>The module's <c>Register</c> method, its assembly attribute and (optionally) the NativeAOT entry point.</summary>
    public static string Module(string module, IReadOnlyList<DataModel> data, IReadOnlyList<SystemModel> systems,
        IReadOnlyList<BehaviourModel> behaviours, IReadOnlyList<CommandModel> commands,
        IReadOnlyDictionary<string, string> types, bool nativeEntry, IReadOnlyList<LinkedModule> linked)
    {
        var cls = ModuleClass(module);
        var c = Header();
        c.Line($"[assembly: global::Ara.Hosting.AraModule({Lit(module)}, typeof(global::Ara.Generated.{cls}))]");
        c.Open("namespace Ara.Generated");
        c.Line($"/// <summary>Registers module <c>{Xml(module)}</c> (generated by Ara.Generators).</summary>");
        c.Open($"public static unsafe class {cls}");
        c.Line("/// <summary>The module name.</summary>");
        c.Line($"public const string Name = {Lit(module)};");
        c.Line("/// <summary>Declares this module's types, components, systems, behaviours and commands.</summary>");
        c.Open("public static void Register(global::Ara.Hosting.ModuleBuilder b)");
        foreach (var kv in types.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            c.Line($"b.Type({Lit(kv.Key)}, {Lit(kv.Value)});");
        foreach (var d in data.OrderBy(d => d.SchemaName, StringComparer.Ordinal))
        {
            var t = d.Shell.FullName;
            c.Line($"b.{d.Role}<{t}>({Lit(d.SchemaName)}, {t}.__AraOffsets(), static i => {t}.__araIndex = i);");
        }
        foreach (var bm in behaviours.OrderBy(b => b.SchemaName, StringComparer.Ordinal))
        {
            var t = bm.Shell.FullName + ".Data";
            c.Line($"b.Component<{t}>({Lit(bm.SchemaName)}, {t}.__AraOffsets(), static i => {t}.__araIndex = i);");
        }
        foreach (var s in systems.OrderBy(s => s.Order).ThenBy(s => s.Name, StringComparer.Ordinal))
        {
            var cols = Access(s.Params.Where(p => p.Kind == "column"));
            var res = Access(s.Params.Where(p => p.Kind == "resource"));
            c.Line($"b.System({Lit(s.Name)}, &{s.Shell.FullName}.__AraRun_{s.Method}, {s.Order}, {cols}, {res}, {Strings(s.With)}, {Strings(s.Without)});");
        }
        foreach (var bm in behaviours.OrderBy(b => b.SchemaName, StringComparer.Ordinal))
            c.Line($"b.Behaviour<{bm.Shell.FullName}, {bm.Shell.FullName}.Data>({Lit(bm.SchemaName)}, {Lit(bm.SchemaName)}, static () => new {bm.Shell.FullName}());");
        foreach (var cm in commands.OrderBy(x => x.Name, StringComparer.Ordinal))
        {
            var comps = cm.Params.Where(p => p.Kind == "component").ToList();
            var reads = Strings(comps.Where(p => p.RefKind != "ref").Select(p => p.SchemaName));
            var writes = Strings(comps.Where(p => p.RefKind == "ref").Select(p => p.SchemaName));
            var expose = cm.Expose is null ? "null" : Lit(cm.Expose);
            c.Line($"b.Command<{cm.Shell.FullName}.Params>({Lit(cm.Name)}, {Lit(cm.Summary)}, {Lit(cm.ParamsType)}, {cm.Shell.FullName}.__AraParamsOffsets(), &{cm.Shell.FullName}.__AraInvoke, {reads}, {writes}, {expose}, {Strings(cm.Examples)});");
        }
        c.Close().Close();
        if (nativeEntry)
        {
            c.Line("/// <summary>The NativeAOT export the Rust host loads (<c>ara_script_init</c>).</summary>");
            c.Open("internal static unsafe class AraNativeEntry");
            c.Line("[global::System.Runtime.InteropServices.UnmanagedCallersOnly(EntryPoint = \"ara_script_init\")]");
            var mods = new List<string> { $"({cls}.Name, new global::System.Action<global::Ara.Hosting.ModuleBuilder>({cls}.Register))" };
            mods.AddRange(linked.Select(l => $"({Lit(l.Name)}, new global::System.Action<global::Ara.Hosting.ModuleBuilder>({l.Entry}.Register))"));
            c.Line("static int Init(global::Ara.Hosting.HostInit* host, global::Ara.Hosting.ScriptApi* api) =>");
            c.Line("    global::Ara.Hosting.ScriptRuntime.Init(host, api, new global::Ara.Hosting.StaticModuleLoader(" + string.Join(", ", mods) + "));");
            c.Close();
        }
        c.Close();
        return c.ToString();
    }

    /// <summary>The generated registration class name for a module (<c>AraModule_Outpost_Sample</c>).</summary>
    public static string ModuleClass(string module) =>
        "AraModule_" + new string(module.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());

    static string Access(IEnumerable<SystemParam> ps) =>
        "[" + string.Join(", ", ps.Select(p => $"new global::Ara.Hosting.ColumnAccess({Lit(p.SchemaName)}, {(p.RefKind == "ref" ? "true" : "false")})")) + "]";

    static string Strings(IEnumerable<string> items) => "[" + string.Join(", ", items.Select(Lit)) + "]";

    /// <summary>A C# string literal.</summary>
    public static string Lit(string s)
    {
        var sb = new StringBuilder("\"");
        foreach (var ch in s)
        {
            switch (ch)
            {
                case '"': sb.Append("\\\""); break;
                case '\\': sb.Append("\\\\"); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                default: sb.Append(ch); break;
            }
        }
        return sb.Append('"').ToString();
    }

    static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    /// <summary>FNV-1a of a name: the stable RNG stream key of a system.</summary>
    public static uint StableHash(string s)
    {
        uint h = 2166136261;
        foreach (var ch in s) h = unchecked((h ^ ch) * 16777619);
        return h;
    }
}
