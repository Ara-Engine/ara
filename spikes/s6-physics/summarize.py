"""Collects evidence/<flavour>/*.json into evidence/summary.md (markdown tables).

Standard library only. Run from the spike folder: python summarize.py
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent / "evidence"
rows = {}
for f in sorted(root.glob("*/*.json")):
    if f.parent.name == "ab":
        continue
    data = json.loads(f.read_text(encoding="utf-8-sig"))
    rows.setdefault(data["scenario"], []).append((f.parent.name, f.stem, data["result"]))

out = ["# S6 evidence summary (generated by summarize.py)", ""]


def table(header, lines):
    out.append("| " + " | ".join(header) + " |")
    out.append("|" + "---|" * len(header))
    for line in lines:
        out.append("| " + " | ".join(str(x) for x in line) + " |")
    out.append("")


def f3(x):
    return f"{x:.3f}" if isinstance(x, (int, float)) else str(x)


if "scale" in rows:
    out.append("## Scale: ms per step (600 steps, dt 1/60)")
    lines = []
    for flavor, _, r in sorted(rows["scale"], key=lambda t: (t[2]["bodies"], t[0], t[2]["engine"], t[2]["threads"])):
        lines.append([
            flavor, r["engine"], r["bodies"], r["threads"],
            f3(r["step_ms_all"]["p50"]), f3(r["step_ms_all"]["p95"]),
            f3(r["step_ms_second_half"]["p50"]), f3(r["step_ms_second_half"]["p95"]),
            r["active_at_end"], r["escaped_bodies"], f3(r["extract_all_ms"]["p50"]),
            f"{r['snapshot_bytes'] / 1e6:.2f}", f3(r["snapshot_save_ms"]), f3(r["snapshot_restore_ms"]),
        ])
    table(["flavour", "engine", "bodies", "threads", "p50", "p95", "p50 (last 5 s)", "p95 (last 5 s)",
           "active at end", "escaped", "extract all ms", "snapshot MB", "save ms", "restore ms"], lines)

if "determinism" in rows:
    out.append("## Determinism")
    lines = []
    for flavor, _, r in rows["determinism"]:
        for sp, cp, (t, snap) in zip(r["same_process"], r["cross_process"], r["snapshot_restore"]):
            lines.append([
                flavor, r["engine"], sp["threads"], sp["run_a"]["final_hash"], sp["identical"],
                cp["children_identical"] and cp["identical_to_in_process"], snap["identical"],
                r["thread_count_invariant"], snap["snapshot_bytes"], f3(snap["save_ms"]), f3(snap["restore_ms"]),
            ])
    table(["flavour", "engine", "threads", "final hash (tick 300)", "same process", "cross process",
           "snapshot/restore", "thread-count invariant", "snapshot bytes", "save ms", "restore ms"], lines)

if "character" in rows:
    out.append("## Character controller")
    lines = []
    for flavor, _, r in rows["character"]:
        for lane in r["lanes"]:
            lines.append([flavor, r["engine"], lane["lane"], "PASS" if lane["pass"] else "FAIL", lane["measured"]])
        lines.append([flavor, r["engine"], "update cost", "",
                      f"p50 {r['update_us_per_character']['p50']:.2f} us, p95 {r['update_us_per_character']['p95']:.2f} us per character"])
    table(["flavour", "engine", "lane", "result", "measured"], lines)

if "stacking" in rows:
    out.append("## Stacking")
    lines = []
    for flavor, _, r in rows["stacking"]:
        lines.append([
            flavor, r["engine"], r["solver_iterations"] or "default", f"{r['pyramid_max_lean_10s'] * 1000:.2f}",
            f"{r['tower_max_lean_10s'] * 1000:.2f}", f3(r["tower_top_height_10s"]),
            "yes" if r["standing_10s"] else "NO", r["all_asleep_at_s"], f3(r["step_ms_first_second"]["p50"]),
        ])
    table(["flavour", "engine", "solver iterations", "pyramid lean mm", "tower lean mm", "tower top y",
           "standing at 10 s", "all asleep at s", "awake step p50 ms"], lines)

if "vehicle" in rows:
    out.append("## Vehicle")
    lines = []
    for flavor, _, r in rows["vehicle"]:
        lines.append([
            flavor, r["engine"], f3(r["speed_at_5s"]), f3(r["distance_at_5s"]), f3(r["lateral_drift_at_5s"]),
            f"{r['heading_change_turn_deg']:.1f}", r["turn_direction"], f"{r['turn_radius_m']:.1f}",
            f3(r["min_up_dot"]), r["mean_wheels_in_contact"], "PASS" if r["pass"] else "FAIL", f3(r["step_ms"]["p50"]),
        ])
    table(["flavour", "engine", "speed 5 s m/s", "distance 5 s m", "lateral drift m", "turn deg", "direction",
           "radius m", "min up dot", "wheels down", "result", "step p50 ms"], lines)

if "queries" in rows:
    out.append("## Queries and FFI (5,000 bodies, single thread)")
    lines = []
    for flavor, _, r in rows["queries"]:
        q = r.get("queries", r)
        noop = r.get("noop_call_ns", "")
        lines.append([
            flavor, q["engine"], f3(noop) if noop != "" else "n/a", f3(q["single_position_read_ns"]),
            f3(q["bulk_read_ns_per_body"]), f3(q["raycast_ns"]), q["raycast_hits"], f3(q["sphere_cast_ns"]),
            q["sphere_cast_hits"],
        ])
    table(["flavour", "engine", "FFI no-op ns", "single read ns", "bulk read ns/body", "raycast ns", "ray hits",
           "sphere cast ns", "sphere hits"], lines)

ab = {}
for f in sorted(root.glob("ab/r*/*/scale-*.json")):
    r = json.loads(f.read_text(encoding="utf-8-sig"))["result"]
    ab.setdefault((f.parent.name, r["engine"], r["bodies"], r["threads"]), []).append(r["step_ms_all"]["p50"])
if ab:
    out.append("## Interleaved A/B (median of per-run p50 ms/step; runs interleaved to cancel load drift)")
    lines = []
    for (flavor, engine, bodies, threads), v in sorted(ab.items(), key=lambda kv: (kv[0][2], kv[0][1], kv[0][0])):
        v = sorted(v)
        lines.append([bodies, threads, engine, flavor, len(v), f3(v[len(v) // 2]), f3(v[0]), f3(v[-1])])
    table(["bodies", "threads", "engine", "flavour", "runs", "median p50", "min p50", "max p50"], lines)

build = root / "build.json"
if build.exists():
    out.append("## Build probes")
    data = json.loads(build.read_text(encoding="utf-8-sig"))
    table(["probe", "clean build s", "touch rebuild s", "exe bytes"],
          [[d["probe"], d["clean_build_s"], d["touch_rebuild_s"], d["exe_bytes"]] for d in data])

(root / "summary.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
print("\n".join(out))
