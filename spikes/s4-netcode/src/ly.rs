type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;
const STEP: Duration = Duration::from_nanos(1_000_000_000 / 60);
const PROTOCOL: u64 = 0xa4a0_0004;

/// Stable slot identity generated by the Ara scene/schema, not a backend entity ID.
#[derive(Component, Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
struct ReplicaId(u16);

/// Authoritative gameplay checkpoint tick; does not determine network scheduling.
#[derive(Component, Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
struct ReplicaTick(u32);

/// Generated recipient predicate scoped to the inventory component only.
#[derive(Component)]
#[component(immutable)]
struct PrivateTo(PeerId);
impl VisibilityFilter for PrivateTo {
    type ClientComponent = RemoteId;
    type Scope = SingleComponent<Inventory>;
    const LIFETIME: ScopeLifetime = ScopeLifetime::WhileVisible;
    fn is_visible(&self, _client: Entity, remote: Option<&RemoteId>) -> bool {
        remote.is_some_and(|remote| remote.0 == self.0)
    }
}

impl MapEntities for MoveInput {
    fn map_entities<M: EntityMapper>(&mut self, _mapper: &mut M) {}
}

struct ControlChannel;
#[derive(Serialize, Deserialize)]
enum ToServer {
    Ready,
    Intent { tick: u32, command: Command },
    FinalAck,
}
#[derive(Serialize, Deserialize)]
enum ToClient {
    Begin { origin: u32 },
    // A digest verifies native component replication; no checkpoint is delivered via messages.
    Final { digest: u64 },
}

/// Every supported policy is validated before generating the upstream registrations.
fn protocol(app: &mut App, server: bool) -> Result<()> {
    Registry::new().validate()?;
    app.component::<ReplicaId>().replicate();
    app.component::<ReplicaTick>().replicate();
    app.component::<Motor>().replicate().predict();
    app.interpolate_with::<Motor>(InterpolationFns::interpolate(|a: Motor, b: Motor, t| {
        Motor {
            x: (a.x as f32 + (b.x - a.x) as f32 * t).round() as i32,
            z: (a.z as f32 + (b.z - a.z) as f32 * t).round() as i32,
        }
    }));
    app.component::<Door>().replicate();
    app.component::<Inventory>().replicate();
    app.component::<Item>().replicate();
    if server {
        app.add_visibility_filter::<PrivateTo>();
    }
    app.register_message::<ToServer>()
        .add_direction(NetworkDirection::ClientToServer);
    app.register_message::<ToClient>()
        .add_direction(NetworkDirection::ServerToClient);
    app.add_channel::<ControlChannel>(ChannelSettings {
        mode: ChannelMode::OrderedReliable(ReliableSettings::default()),
        ..Default::default()
    })
    .add_direction(NetworkDirection::Bidirectional);
    app.add_plugins(InputPlugin::<MoveInput> {
        config: lightyear::input::config::InputConfig {
            send_interval: STEP,
            packet_redundancy: 24,
            ..Default::default()
        },
    });
    Ok(())
}

fn base(server: bool) -> Result<App> {
    let mut app = App::new();
    app.add_plugins(bevy_state::app::StatesPlugin);
    if server {
        app.add_plugins(lightyear::prelude::server::ServerPlugins {
            tick_duration: STEP,
        });
    } else {
        app.add_plugins(lightyear::prelude::client::ClientPlugins {
            tick_duration: STEP,
        });
    }
    protocol(&mut app, server)?;
    app.finish();
    app.cleanup();
    Ok(app)
}

fn digest(snapshot: &Snapshot) -> u64 {
    // A diagnostic digest, not the gameplay codec or a way to repair a replica.
    let bytes = postcard::to_allocvec(snapshot).expect("bounded scene snapshot is serializable");
    bytes.into_iter().fold(0xcbf2_9ce4_8422_2325, |hash, byte| {
        (hash ^ u64::from(byte)).wrapping_mul(0x100_0000_01b3)
    })
}

fn send(world: &mut World, link: Entity, message: ToClient) {
    world
        .get_mut::<MessageSender<ToClient>>(link)
        .expect("registered sender on a connected link")
        .send::<ControlChannel>(message);
}

